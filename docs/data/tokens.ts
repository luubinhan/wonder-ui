/** Flat list of every CSS variable for lookup by name. */
export const allCssVars: CssVar[] = tokenGroups.flatMap((group) => group.vars);

function pick(names: string[]): CssVar[] {
  const map = new Map(allCssVars.map((v) => [v.name, v]));
  return names.map((name) => map.get(name)!).filter(Boolean);
}

